const curve = (
	x0: number,
	y0: number,
	a: number,
	b: number,
	c: number,
	d: number,
	x: number,
	y: number
): Path => [
	['M', x0, y0],
	['C', a, b, c, d, x, y]
];
const closed = (...cmds: PathCmd[]): Path => [...cmds, ['Z']];

/** Eight round petals around a centre. */
const petals = (cx: number, cy: number): Path[] =>
	Array.from({ length: 8 }, (_, i) => {
		const a = (i / 8) * Math.PI * 2;
		return circle(cx + Math.cos(a) * 105, cy + Math.sin(a) * 105, 50);
	});

