// Journey traceability: journeys/registry.json lists the family journeys and their steps;
// this script ties them to the Playwright tests (tagged @Jx.y) and to docs/journeys.md.
//
//   node scripts/journeys/trace.mjs           check everything, print every step with its tests
//   node scripts/journeys/trace.mjs --write   regenerate the tables in docs/journeys.md
//   node scripts/journeys/trace.mjs --tests <file>   read `playwright test --list --reporter=json`
//                                             output from a file instead of running it
//
// It exits 1 when:
// - the registry is malformed (ids out of order, unknown status, persona or device)
// - a built step has no test (a tagged Playwright test, or a file in its `tests`) and no
//   `untested` reason; or has an `untested` reason and a test (remove the reason)
// - a planned step has a test
// - a tag or test.step id in tests/e2e names a journey or step the registry does not have
// - the generated part of docs/journeys.md is out of date (run with --write)
//
// A device a step must work on but has no tagged test for is printed as a gap. Gaps are
// reported, not failures: the iPhone and iPad projects run only the IOS_SPECS list.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const BEGIN = '<!-- journeys:begin (generated by scripts/journeys/trace.mjs --write) -->';
export const END = '<!-- journeys:end -->';
const STATUSES = ['built', 'planned'];

export function loadRegistry(file = path.join(root, 'journeys/registry.json')) {
	return JSON.parse(fs.readFileSync(file, 'utf8'));
}

/** Playwright's `--list --reporter=json` output -> [{ id, file, title, project }] per tagged id. */
export function tagsFromListing(listing) {
	const found = [];
	const walk = (suite) => {
		for (const spec of suite.specs ?? []) {
			const ids = (spec.tags ?? []).filter((t) => /^J\d+(\.\d+)?$/.test(t));
			for (const t of spec.tests ?? []) {
				for (const id of ids) {
					found.push({ id, file: spec.file, title: spec.title, project: t.projectName });
				}
			}
		}
		for (const child of suite.suites ?? []) walk(child);
	};
	for (const s of listing.suites ?? []) walk(s);
	return found;
}

/** test.step('J4.2 ...') names in a spec's source. */
export function stepIdsInSource(source) {
	return [...source.matchAll(/test\.step\(\s*['"`](J\d+\.\d+)\b/g)].map((m) => m[1]);
}

export function checkRegistry(reg) {
	const problems = [];
	const devices = Object.keys(reg.devices ?? {});
	reg.journeys.forEach((j, ji) => {
		if (j.id !== `J${ji}`) problems.push(`journey ${j.id} should be J${ji}`);
		if (!reg.personas.includes(j.persona)) problems.push(`${j.id}: unknown persona "${j.persona}"`);
		for (const d of j.devices ?? [])
			if (!devices.includes(d)) problems.push(`${j.id}: unknown device "${d}"`);
		j.steps.forEach((s, si) => {
			if (s.id !== `${j.id}.${si + 1}`) problems.push(`step ${s.id} should be ${j.id}.${si + 1}`);
			if (!STATUSES.includes(s.status)) problems.push(`${s.id}: status must be built or planned`);
			for (const d of s.devices ?? [])
				if (!devices.includes(d)) problems.push(`${s.id}: unknown device "${d}"`);
		});
	});
	return problems;
}

export function stepDevices(reg, journey, step) {
	return (step.devices ?? journey.devices ?? []).flatMap((d) => reg.devices[d]);
}

/** Pure analysis: registry + tagged tests + extra tags/step ids -> trace rows, problems, gaps. */
export function analyze(reg, tagged, { stepIds = [], fileExists = () => true } = {}) {
	const problems = checkRegistry(reg);
	const known = new Set();
	for (const j of reg.journeys) {
		known.add(j.id);
		for (const s of j.steps) known.add(s.id);
	}
	for (const t of tagged) {
		if (!known.has(t.id))
			problems.push(`tag @${t.id} in ${t.file} ("${t.title}") names no journey or step`);
	}
	for (const { id, file } of stepIds) {
		if (!known.has(id)) problems.push(`test.step "${id}" in ${file} names no journey or step`);
	}
	const rows = [];
	for (const j of reg.journeys) {
		for (const s of j.steps) {
			const mine = tagged.filter((t) => t.id === s.id);
			const files = [...new Set([...mine.map((t) => t.file), ...(s.tests ?? [])])].sort();
			const projects = new Set(mine.map((t) => t.project));
			const stepsTagged = stepIds.filter((x) => x.id === s.id).map((x) => x.file);
			const hasTest = files.length > 0 || stepsTagged.length > 0;
			for (const f of s.tests ?? [])
				if (!fileExists(f)) problems.push(`${s.id}: tests file ${f} does not exist`);
			if (s.status === 'built' && !hasTest && !s.untested) {
				problems.push(
					`${s.id} is built but has no tagged test (tag one @${s.id} or give an "untested" reason)`
				);
			}
			if (s.status === 'built' && hasTest && s.untested) {
				problems.push(
					`${s.id} has tests, so drop its "untested" reason (use "simulated" for a caveat)`
				);
			}
			if (s.status === 'planned' && hasTest) problems.push(`${s.id} is planned but has tests`);
			const gaps =
				s.status === 'built' && mine.length
					? stepDevices(reg, j, s).filter((p) => !projects.has(p))
					: [];
			rows.push({ journey: j, step: s, files, gaps, tested: hasTest });
		}
	}
	return { problems, rows };
}

const short = (f) => f.replace(/^tests\/e2e\//, '').replace(/\.e2e\.ts$/, '');
const cell = (s) => String(s).replace(/\|/g, '\\|');

export function summarize(reg, rows) {
	const built = rows.filter((r) => r.step.status === 'built');
	return {
		journeys: reg.journeys.length,
		critical: reg.journeys.filter((j) => j.critical).length,
		steps: rows.length,
		built: built.length,
		planned: rows.length - built.length,
		tested: built.filter((r) => r.tested).length,
		untested: built.filter((r) => !r.tested).length,
		gaps: rows.filter((r) => r.gaps.length).length
	};
}

/** The generated section of docs/journeys.md. Lists spec files, never counts, so it only changes with the registry. */
export function renderDocs(reg, rows) {
	const out = [
		'| Step | What happens | Status | Devices | Tests |',
		'| --- | --- | --- | --- | --- |'
	];
	for (const j of reg.journeys) {
		const crit = j.critical ? ', critical' : '';
		out.push(`| **${j.id}** | **${cell(j.name)}** (${j.persona}${crit}) | | | |`);
		for (const r of rows.filter((x) => x.journey === j)) {
			const s = r.step;
			const devs = (s.devices ?? j.devices ?? []).join(', ');
			let tests = r.files.map((f) => '`' + short(f) + '`').join(', ');
			if (!tests) tests = s.status === 'planned' ? 'planned' : `untested: ${cell(s.untested)}`;
			if (s.simulated) tests += `. Simulated: ${cell(s.simulated)}`;
			out.push(`| ${s.id} | ${cell(s.text)} | ${s.status} | ${devs} | ${tests} |`);
		}
	}
	return out.join('\n');
}

export function spliceDocs(doc, generated) {
	const b = doc.indexOf(BEGIN);
	const e = doc.indexOf(END);
	if (b < 0 || e < b) return null;
	return `${doc.slice(0, b)}${BEGIN}\n\n${generated}\n\n${doc.slice(e)}`;
}

export function listTests(file) {
	const raw = file
		? fs.readFileSync(file, 'utf8')
		: execFileSync('pnpm', ['exec', 'playwright', 'test', '--list', '--reporter=json'], {
				cwd: root,
				encoding: 'utf8',
				maxBuffer: 256 * 1024 * 1024,
				stdio: ['ignore', 'pipe', 'ignore']
			});
	return JSON.parse(raw);
}

function scanSteps() {
	const dir = path.join(root, 'tests/e2e');
	return fs
		.readdirSync(dir)
		.filter((f) => f.endsWith('.ts'))
		.flatMap((f) =>
			stepIdsInSource(fs.readFileSync(path.join(dir, f), 'utf8')).map((id) => ({
				id,
				file: `tests/e2e/${f}`
			}))
		);
}

const out = (line) => process.stdout.write(`${line}\n`);

function main(argv) {
	const write = argv.includes('--write');
	const ti = argv.indexOf('--tests');
	const reg = loadRegistry();
	const tagged = tagsFromListing(listTests(ti >= 0 ? argv[ti + 1] : undefined));
	const { problems, rows } = analyze(reg, tagged, {
		stepIds: scanSteps(),
		fileExists: (f) => fs.existsSync(path.join(root, f))
	});
	const docPath = path.join(root, 'docs/journeys.md');
	const doc = fs.readFileSync(docPath, 'utf8');
	const next = spliceDocs(doc, renderDocs(reg, rows));
	if (next === null) problems.push('docs/journeys.md has no journeys:begin / journeys:end markers');
	else if (write) {
		fs.writeFileSync(docPath, next);
		out('wrote docs/journeys.md');
	} else if (next !== doc)
		problems.push('docs/journeys.md is out of date: run node scripts/journeys/trace.mjs --write');

	for (const j of reg.journeys) {
		out(`\n${j.id} ${j.name} [${j.persona}${j.critical ? ', critical' : ''}]`);
		for (const r of rows.filter((x) => x.journey === j)) {
			const mark = r.step.status === 'planned' ? 'planned ' : r.tested ? 'tested  ' : 'UNTESTED';
			const files =
				r.files.map(short).join(', ') || (r.step.untested ? `(${r.step.untested})` : '');
			out(
				`  ${r.step.id.padEnd(6)} ${mark} ${files}${r.gaps.length ? `  [no test on: ${r.gaps.join(', ')}]` : ''}`
			);
		}
	}
	const sum = summarize(reg, rows);
	out(
		`\n${sum.journeys} journeys (${sum.critical} critical), ${sum.steps} steps: ${sum.built} built, ${sum.planned} planned; ` +
			`built steps ${sum.tested} tested, ${sum.untested} untested; ${sum.gaps} steps with a device gap`
	);
	if (problems.length) {
		console.error(`\n${problems.length} problem(s):`);
		for (const p of problems) console.error(`  - ${p}`);
		process.exitCode = 1;
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
	main(process.argv.slice(2));
